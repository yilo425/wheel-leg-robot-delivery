//=============================================================================
// module : i2c_bus_arb
// layer  : driver
//-----------------------------------------------------------------------------
// 功能 : **把多个 I2C 从设备驱动挂到同一条 I2C 总线上**的仲裁器。
//
//   为什么需要它：
//     tof_driver(VL53L0X @0x29) 和 imu_driver(MPU6050 @0x68) 各自**内部**都例化了
//     一份 i2c_master。如果两份 master 直接挂到同一条 scl/sda 上，两者会同时
//     发起传输、互相打断 —— 读回的数据是坏的，而且**不会报错**（只表现为
//     "偶尔读到垃圾值"）。`i2c_master.v` 头注释里说"TOF 和 MPU6050 共用一路 I2C"
//     是意图，但必须有仲裁器才能落实。
//
//-----------------------------------------------------------------------------
// 为什么不是"引脚级 mux"
//-----------------------------------------------------------------------------
//   I2C 是**开漏**总线：每个器件只会"拉低"或"释放"，靠外部上拉拉高。
//   所以两份 master 的 scl/sda **本来就可以直接并到同一条线上**（线与），
//   电气上不需要任何 mux。真正缺的只有一件事：**同一时刻只允许一个 master 说话**。
//   本模块就只做这件事 —— 授权（grant）。
//
//   （另一个方案是"内部三态 mux"，但 FPGA 内部没有三态资源，综合会出问题，
//     所以这里走"线与 + 授权"的路子。）
//
//-----------------------------------------------------------------------------
// 接口约定（配合 tof_driver / imu_driver 的 bus_grant/bus_req/bus_busy）
//-----------------------------------------------------------------------------
//   每个驱动给出：
//       bus_req  = 有排队事务、想用总线（驱动内部 = t_pending）
//       bus_busy = 一笔事务正在总线上进行（驱动内部 = t_busy）
//   本模块给出：
//       bus_grant = 1 才允许该驱动发 start（驱动内部已做门控）
//
//   时序（关键，写清楚免得以后改坏）：
//       T    : 驱动 A 拉 bus_req
//       T+1  : 仲裁器把 grant 给 A（owner<=A，寄存器输出）
//       T+2  : 驱动 A 看到 grant，发 start，t_busy 起来 -> busy0=1
//       ...  : 事务进行中，grant 保持（因为 busy0=1）
//       结束 : 驱动 A 的 t_busy 落下 -> 仲裁器释放 owner，可以给下一个
//   ⚠️ 所以 grant 是**电平**、且必须"占用期间不切换"：靠 busy 判断。
//      只看 req 是不够的 —— req 在发车那一拍就掉了。
//
//-----------------------------------------------------------------------------
// 仲裁策略
//-----------------------------------------------------------------------------
//   轮询（round-robin）：两个同时请求时，上次没被服务的优先。
//   避免固定优先级把 IMU 饿死（TOF 每次采样之间有大段 D_WAIT 空档，
//   固定优先级其实也够，但轮询更稳）。
//
//   ⚠️ 死锁是不可能的：两个驱动内部都有超时（TOF 的 TIMEOUT_MS、
//      i2c_master 自己的单笔超时），最坏情况是某一方事务超时后
//      t_busy 落下、grant 被释放，另一方继续。
//
//=============================================================================
`timescale 1ns/1ps

module i2c_bus_arb #(
    //----------------------------------------------------------------
    // 参数自检开关（只有 initial 里的 $display，综合器忽略）
    //----------------------------------------------------------------
    parameter integer _ASSERT_EN = 1
) (
    input  wire clk,
    input  wire rst_n,          // 低有效

    //---------------- 申请方 0（例如 tof_driver）----------------
    input  wire req0,           // 1 = 想用总线
    input  wire busy0,          // 1 = 事务进行中（占用总线）
    output reg  grant0,         // 1 = 获准

    //---------------- 申请方 1（例如 imu_driver）----------------
    input  wire req1,
    input  wire busy1,
    output reg  grant1
);

    //================================================================
    // 仲裁状态
    //================================================================
    localparam [1:0] O_IDLE = 2'd0,
                     O_0    = 2'd1,   // 总线归申请方 0
                     O_1    = 2'd2;   // 总线归申请方 1

    reg [1:0] owner;
    reg       last;      // 上次服务的是谁：0 或 1（轮询用）

    //================================================================
    // 仲裁 FSM
    //================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            owner <= O_IDLE;
            last  <= 1'b0;
        end else begin
            case (owner)
                //--------------------------------------------------
                // 空闲：谁请求给谁；两个都请求 -> 让上次没服务的先
                //--------------------------------------------------
                O_IDLE: begin
                    if (req0 && req1) begin
                        // last==1（上次服务的是 1）-> 这次给 0
                        owner <= last ? O_0 : O_1;
                    end else if (req0) begin
                        owner <= O_0;
                    end else if (req1) begin
                        owner <= O_1;
                    end
                end

                //--------------------------------------------------
                // 归 0：事务进行中不切换
                //
                //   ★ 释放条件必须是「**既没请求、也不忙**」，不能只看 !busy0：
                //     驱动"决定发车"的那一拍，t_pending 还没清掉、t_busy 还没起来
                //     （都是非阻塞赋值，下一拍才生效）。此时若只判 !busy0，
                //     仲裁器会当场误释放 -> 另一个驱动立刻被授权 -> **两个 master
                //     同时驱动总线**，读回的数据被写脏（实测表现：MPU 的寄存器里
                //     出现了 VL53L0X tuning 表里的 0x44，且两边初始化都跑不完）。
                //     加上 !req0 后：发车那一拍 req0 仍是 1，grant 被稳稳保住。
                //
                //   这个条件也天然防死锁：驱动超时用 t_clr 丢掉排队请求后
                //   req/busy 同时为 0，grant 会被释放，另一个驱动可以继续。
                //--------------------------------------------------
                O_0: begin
                    if (!req0 && !busy0) begin
                        last  <= 1'b0;      // 记住"服务过 0"
                        owner <= O_IDLE;
                    end
                end

                //--------------------------------------------------
                // 归 1：同上
                //--------------------------------------------------
                O_1: begin
                    if (!req1 && !busy1) begin
                        last  <= 1'b1;
                        owner <= O_IDLE;
                    end
                end

                default: owner <= O_IDLE;
            endcase
        end
    end

    //================================================================
    // 授权输出（互斥：同一时刻最多一个为 1）
    //================================================================
    always @(*) begin
        grant0 = (owner == O_0);
        grant1 = (owner == O_1);
    end

    //================================================================
    // 参数自检
    //================================================================
    initial begin
        if (_ASSERT_EN == 1) begin
            $display("[i2c_bus_arb] 轮询仲裁，2 个申请方");
        end
    end

endmodule
