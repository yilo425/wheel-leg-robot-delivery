//=============================================================================
// module : stance_ctrl
// brief  : 站立高度控制（遥控"升高/降低"）
//
//-----------------------------------------------------------------------------
// 需求（2026-10-30）
//-----------------------------------------------------------------------------
//   * 升高 = 0 状态（装配中立位，1.5ms）
//   * 降低：前腿两只舵机顺时针 45°，后腿两只逆时针 45°
//   * 升高：反向
//   * 旋转要慢（限制电流）
//   * 低位时再按"降低"不动；高位时再按"升高"不动（天然由 pos 饱和实现）
//
//-----------------------------------------------------------------------------
// 脉冲宽度（PCA9685 计数，50Hz 下 1 计数 ≈ 4.88us）
//-----------------------------------------------------------------------------
//   中立位 1.5ms -> 307 计数
//   45°     -> 约 0.5ms -> 102 计数
//
//   升高（pos=0）   ：前 307、后 307
//   降低（pos=102） ：前 409（2.0ms，顺时针）、后 205（1.0ms，逆时针）
//
//   ★ 前后反向是必须的：车体要整体下降，前腿往前压、后腿往后压。
//
//-----------------------------------------------------------------------------
// 为什么用"位置级进"而不是一次跳变
//-----------------------------------------------------------------------------
//   舵机瞬时改变 45° 会拉大电流（4 只同时 ≈ 3A+），而且机械冲击大。
//   这里每 STEP_MS 只走 1 个计数，102 步 ≈ 2 秒，电流平稳。
//=============================================================================
`default_nettype none

module stance_ctrl #(
    parameter integer CLK_FREQ_HZ = 50_000_000,
    parameter integer STEP_MS     = 20,     // 每 20ms 走 1 计数 -> 102 步 ≈ 2.04s
    parameter integer CNT_MID     = 307,    // 1.5ms 中立位
    parameter integer CNT_SPAN    = 102,    // 45° 对应的计数
    // ★ 2026-10-30：旋转方向开关
    //   舵机反向安装（轴往后挪、让腿和前缘平齐、力臂更小）后，
    //   同样的"降低"需要相反的脉冲方向 -> 这里置 1 即可，不用改接线也不用改页面。
    parameter integer INVERT      = 0,
    // ★ 2026-10-30：装配补偿。上电（0 状态）时腿并不垂直，
    //   而是向外撅 30°。这里把中立位整体偏移一下抵消它：
    //   30° ≈ 333us ≈ 68 个计数（一计数 ≈ 4.88us，45° ≈ 102 计数）
    //   调成 0 就回到修正前的行为。
    // ★ 2026-11-02：再加 5° 向内修正（腿向外撅）。
    //   68 个计数 = 30°；5° ≈ 102*5/45 ≈ 11.3 -> 取 11
    //   68 + 11 = 79（约 35°）。要变回去改回 68。
    parameter integer LEVEL_CNT   = 90
)(
    input  wire        clk,
    input  wire        rst_n,
    input  wire        target_low,      // 1=要降到低位, 0=要升到高位（0 状态）
    output wire [11:0] cnt_front,       // 通道 0/1 的计数值
    output wire [11:0] cnt_rear,        // 通道 2/3 的计数值
    output wire [7:0]  pos_pct,         // 当前位置百分比 0(高)~100(低)，调试用
    output wire        at_low,          // 1=已到低位
    output wire        at_high          // 1=已到高位
);

    //=========================================================================
    // 1) 步进节拍
    //=========================================================================
    localparam integer TICK_MAX = (CLK_FREQ_HZ / 1000) * STEP_MS;

    reg [31:0] tick_cnt;
    reg        tick;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            tick_cnt <= 32'd0;
            tick     <= 1'b0;
        end else if (tick_cnt >= TICK_MAX - 1) begin
            tick_cnt <= 32'd0;
            tick     <= 1'b1;
        end else begin
            tick_cnt <= tick_cnt + 32'd1;
            tick     <= 1'b0;
        end
    end

    //=========================================================================
    // 2) 位置级进（0 .. CNT_SPAN）
    //    饱和之后自然就是"再按也没用"，正好满足限位要求
    //=========================================================================
    reg [11:0] pos;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            pos <= 12'd0;                       // 上电 = 高位（0 状态）
        else if (tick) begin
            if (target_low) begin
                if (pos < CNT_SPAN[11:0])
                    pos <= pos + 12'd1;         // 慢慢降
            end else begin
                if (pos > 12'd0)
                    pos <= pos - 12'd1;         // 慢慢升
            end
        end
    end

    //=========================================================================
    // 3) 输出：前腿 +、后腿 −（一升一降，车体整体下压）
    //=========================================================================
    // ★ 2026-10-30：中立位先加装配补偿 LEVEL_CNT（0 状态腿垂直），再叠加升降位置 pos。
    //   补偿方向和"降低"相反（降低会让腿更外撅，所以要往反方向贴）
    wire [11:0] mid_f = (INVERT != 0) ? (CNT_MID[11:0] + LEVEL_CNT[11:0])
                                      : (CNT_MID[11:0] - LEVEL_CNT[11:0]);
    wire [11:0] mid_r = (INVERT != 0) ? (CNT_MID[11:0] - LEVEL_CNT[11:0])
                                      : (CNT_MID[11:0] + LEVEL_CNT[11:0]);

    assign cnt_front = (INVERT != 0) ? (mid_f - pos) : (mid_f + pos);
    assign cnt_rear  = (INVERT != 0) ? (mid_r + pos) : (mid_r - pos);

    assign pos_pct = (pos * 12'd100) / CNT_SPAN[11:0];

    assign at_low  = (pos >= CNT_SPAN[11:0]);
    assign at_high = (pos == 12'd0);

endmodule

`default_nettype wire
