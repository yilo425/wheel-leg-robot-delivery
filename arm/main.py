# -*- coding: utf-8 -*-
"""
main.py -- 开机自动启动 WiFi 遥控（K230 侧）

=============================================================================
什么时候用
=============================================================================
拔掉 USB 之后没有控制台（REPL）了，所以只能靠"开机自动运行 main.py"
把遥控程序拉起来。这个文件就是干这个的。

=============================================================================
怎么用
=============================================================================
1) 卡里原来的 main.py 先改名备份成 main_vision.py
2) 把这个文件复制到卡里，并改名成 main.py
3) 拔 USB -> 断电 -> 重新上电

=============================================================================
为什么里面有一堆 try/except
=============================================================================
拔了 USB 就没有串口输出了，程序一旦报错你完全看不到现象。
所以这里把"走到哪一步""报了什么错"全写到卡里的文本文件：

    /sdcard/rc_boot.txt  -- 启动日志（每行一步，能看出卡在哪）
    /sdcard/rc_err.txt   -- 完整 traceback（出异常才有）

排查时把 USB 插回电脑，打开 CanMV\\sdcard\\ 直接看这两个文件就行。

=============================================================================
正常的 rc_boot.txt 应该长这样
=============================================================================
    --- boot ---
    wifi_rc imported
    [信息] 已发送 CONFIG 0x20=1（手动模式）     <- 这行也可能先进 rc_boot
    ...

如果只有 "--- boot ---" 就没了 -> import wifi_rc 卡住了/失败了
如果出现 "EXCEPTION: ..."       -> 看 rc_err.txt
"""

import sys


#-----------------------------------------------------------------------------
# 日志：写文件，失败就算了（绝不能因为写日志把主流程搞挂）
#-----------------------------------------------------------------------------
def _log(msg):
    try:
        with open('/sdcard/rc_boot.txt', 'a') as f:
            f.write(str(msg) + '\n')
    except Exception:
        pass


#-----------------------------------------------------------------------------
# 启动日志太大就清掉（反复上电不会把卡写满）
#-----------------------------------------------------------------------------
try:
    import os
    if os.stat('/sdcard/rc_boot.txt')[6] > 4000:
        os.remove('/sdcard/rc_boot.txt')
except Exception:
    pass

_log('--- boot ---')

#-----------------------------------------------------------------------------
# 真正干活
#-----------------------------------------------------------------------------
try:
    import wifi_rc

    _log('wifi_rc imported OK')
    _log('starting run() ...')

    wifi_rc.run()

    # run() 本该是死循环，能走到这里说明它提前返回了
    _log('WARN: run() returned unexpectedly')

except Exception as e:
    _log('EXCEPTION: ' + repr(e))
    try:
        with open('/sdcard/rc_err.txt', 'w') as f:
            sys.print_exception(e, f)
    except Exception:
        pass
