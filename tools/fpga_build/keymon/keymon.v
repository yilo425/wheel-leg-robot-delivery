//=============================================================================
// keymon.v -- 按键/引脚监视器（诊断用，不是产品固件）
//
// 目的：确定性地回答"为什么按 S0 状态机不动"。
//
//   led[0] = S0 (F15) 实时电平：亮 = 松开(高)，灭 = 按住(低)
//   led[1] = S1 (A20) 实时电平
//   led[2] = S4 (B21) 实时电平（复位键）
//   led[3] = 任一键被按下时亮（= 三个里有一个是 0）
//
// 用法：按下每个键，看对应的灯是否熄灭。
//   对应灯会灭 -> 按键和引脚都正常，问题在状态机逻辑
//   对应灯不变 -> 该键/该引脚有问题（坏的键、或丝印与引脚不符）
//=============================================================================
module keymon (
    input  wire       clk_50m,
    input  wire [1:0] key,        // key[0]=S0(F15)  key[1]=S1(A20)
    input  wire       rst_key_n,  // S4(B21)
    output wire [3:0] led
);

    // 三级同步（异步输入 -> 时钟域），同时也滤掉很短的毛刺
    reg [2:0] k0, k1, k2;
    always @(posedge clk_50m) begin
        k0 <= {k0[1:0], key[0]};
        k1 <= {k1[1:0], key[1]};
        k2 <= {k2[1:0], rst_key_n};
    end

    assign led[0] = k0[2];                       // S0：亮=松开
    assign led[1] = k1[2];                       // S1：亮=松开
    assign led[2] = k2[2];                       // S4：亮=松开
    assign led[3] = ~(k0[2] & k1[2] & k2[2]);    // 任一按下就亮

endmodule
