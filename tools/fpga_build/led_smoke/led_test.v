//=============================================================================
// led_test.v -- 上板冒烟测试（最小设计）
//-----------------------------------------------------------------------------
// 目的：一次确认三件事
//   1) 工具链能跑通（综合 / 布局布线 / 生成比特流）
//   2) 引脚分配是对的（时钟、复位键、4 个 LED）
//   3) 板子活着
//
// 现象：
//   * 上电后 4 个 LED 轮流点亮（每 0.125s 移一格）
//   * 按住 S4 复位键 -> 全灭（验证按键通路）
//
// 板卡：小梅哥 ACG720 / **GW5AT-138**（⚠️ 不是 GW5AST-138：ID 差一位，
//       本板实测 ID = 0x0011081B = GW5AT-138，见 doc/board_pinout.md 第 2 节）
//   clk_50m   Y18
//   rst_key_n B21  (S4 按键，低有效)
//   led[3:0]  M22 N22 L21 K21
//=============================================================================
`timescale 1ns/1ps

module led_test (
    input  wire       clk_50m,
    input  wire       rst_key_n,
    output wire [3:0] led
);

    // 50MHz 数到 6_249_999 = 0.125s
    reg [24:0] cnt = 25'd0;
    reg [3:0]  pat = 4'b0001;

    always @(posedge clk_50m) begin
        if (cnt == 25'd6_249_999) begin
            cnt <= 25'd0;
            pat <= {pat[2:0], pat[3]};      // 循环左移一格
        end else begin
            cnt <= cnt + 25'd1;
        end
    end

    // S4 是低有效按键：松开=1 显示流水，按下=0 全灭
    assign led = rst_key_n ? pat : 4'b0000;

endmodule