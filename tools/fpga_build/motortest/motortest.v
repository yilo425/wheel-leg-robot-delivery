//=============================================================================
// motortest.v (v4) -- 5V 供电专用电机自测
//
// v3 的问题：40% 占空比在 5V 供电下只有 2V，MG310 转不动（不是坏，是电压不够）。
//
// v4 改成：**100% 占空比**，但每次只给 **0.3 秒**，然后停 1.7 秒。
//   为什么限时：5V 来自 FPGA 的 USB 口（约 500mA），
//   电机堵转/启动瞬间电流大，长时间 100% 会把 USB 拉爆导致 FPGA 重启。
//   0.3 秒的脉冲足够看清"转不转"，平均电流又很低。
//
// ⚠️⚠️ 这一版**只能配 5V 供电**！
//       接到 12V 电池上就是 100% × 12V = 12V 直加电机（额定 7.4V）→ 过压。
//
// 引脚：
//     A13 = PWMA   A18 = AIN1     （A 通道）
//     A14 = PWMB   A19 = BIN1     （B 通道，方便把电机挪过去对比）
//     E18 = 探针（读驱动板 3V3）
//     STBY 由板上内部上拉 -> 悬空即可
//
// 灯：
//     D0 = 输出窗口（亮 0.3 秒 / 灭 1.7 秒）
//     D1 = 探针（板子 3V3 有电）
//     D2 = 同 D0（PWM 波形，这里是 100% 所以和 D0 一样）
//     D3 = 常亮（活着）
//=============================================================================
module motortest (
    input  wire       clk_50m,
    input  wire       probe,     // -> E18
    output wire       pwm_a,     // -> A13
    output wire       dir_a,     // -> A18
    output wire       pwm_b,     // -> A14
    output wire       dir_b,     // -> A19
    output wire [3:0] led
);

    //------------------------------------------------------------------
    // 2 秒周期：前 0.3 秒输出，后 1.7 秒停止
    //   50MHz -> 100_000_000 拍 = 2 秒（27 位够）
    //   0.3 秒 = 15_000_000 拍
    //------------------------------------------------------------------
    reg [26:0] t;

    always @(posedge clk_50m) begin
        if (t >= 27'd99_999_999) t <= 27'd0;
        else                     t <= t + 27'd1;
    end

    wire on = (t < 27'd15_000_000);        // 前 0.3 秒

    assign pwm_a  = on;                    // 100% 占空比
    assign pwm_b  = on;
    assign dir_a  = 1'b1;                  // AIN1 = 1（AIN2 接 GND -> 正转）
    assign dir_b  = 1'b1;                  // BIN1 = 1（BIN2 接 GND）

    //------------------------------------------------------------------
    // 探针同步
    //------------------------------------------------------------------
    reg [1:0] probe_sync;
    always @(posedge clk_50m) begin
        probe_sync <= {probe_sync[0], probe};
    end

    //------------------------------------------------------------------
    // 灯
    //------------------------------------------------------------------
    assign led[0] = on;                    // 输出窗口
    assign led[1] = probe_sync[1];         // 探针
    assign led[2] = on;                    // 同输出（100% 占空比）
    assign led[3] = 1'b1;                  // 活着

endmodule
