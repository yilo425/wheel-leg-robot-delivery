//=============================================================================
// tb : tb_gowin_prim
//-----------------------------------------------------------------------------
// 目的: **工具链冒烟测试** —— 证明"Gowin 原语库 ↔ ModelSim"这条链真的通了。
//
//   为什么需要这条 tb：
//     工程里其他 tb 跑的都是**纯 RTL**，一个 Gowin 原语都不用
//     （clk_gen 默认 BYPASS=1，是纯连线）。
//     也就是说：**就算 Gowin 原语库根本没挂上、或者挂的是别的版本的库，
//       429 项回归照样全 PASS** —— 因为没人去碰原语。
//     等哪天真要上 PLL（clk_gen 的 BYPASS=0），才会突然报
//         Instantiation of 'PLL' failed. The design unit was not found
//     那时候再查就晚了。
//
//   本条 tb 就是把这个洞补上：它**故意**去例化几个真实原语，
//   只要原语库缺失/版本不对/路径不对，它就会编译或 elaborate 失败，
//   在回归里**当场红**。
//
//-----------------------------------------------------------------------------
// 覆盖的原语（都取自 <Gowin>\IDE\simlib\gw5a\prim_sim.v）
//-----------------------------------------------------------------------------
//   LUT4   组合查表 —— 验证 INIT 位序（I0 是最低位）和基本组合行为
//   IOBUF  三态双向缓冲 —— 验证 OEN 方向控制 + 释放后靠上拉 + O 跟随 IO
//   GSR    全局复位 —— 只有输入没有输出，例化成功即证明该单元可解析
//   OSC    内部振荡器 —— 验证它真的在翻转（原语库"活着"的最直接证据）
//
//   ⚠️ 这里**故意不含 PLL**：GW5A 的 PLL 模型会按参数实时算出时钟周期，
//      参数配错时可能出现 0 周期（`#0` 死循环 → 整个仿真挂住）。
//      PLL 属于"要上真 PLL 时再单独验"的东西，做法见
//      doc/toolchain_gowin_modelsim.md。本 tb 只要保证**库本身可用**。
//
//-----------------------------------------------------------------------------
// 怎么判断"库是哪个版本建的"（本次踩过的坑，写在这里免得再踩）
//-----------------------------------------------------------------------------
//   Gowin **V1.9.12 把 `DQS` 从 prim_sim.v 里移出去了**（挪进了
//   DQS_*.vp），而 V1.9.11 的 prim_sim.v 里**有** DQS。
//   所以：
//       库里有 DQS  -> 这是 V1.9.11 建的（**过期**，仿真模型和综合器不是一个版本）
//       库里没 DQS  -> V1.9.12 建的（正确）
//   查法：
//       vdir -lib %MODELSIM_LIB%\gw5a | findstr /C:"MODULE DQS"
//
// 运行: vsim -c -voptargs=+acc -L work -L gw5a work.tb_gowin_prim
// 结果: gowin_prim_result.txt
//=============================================================================
`timescale 1ns/1ps

module tb_gowin_prim;

    //------------------------------------------------------------------
    // 时钟（50MHz）
    //------------------------------------------------------------------
    localparam integer CLK_PERIOD = 20;
    reg clk = 1'b0;
    always #(CLK_PERIOD/2) clk = ~clk;

    integer errors = 0;
    integer checks = 0;
    integer log_fd;

    //==================================================================
    // 1) LUT4 —— 组合查表
    //
    //   prim_sim.v 里的实现：
    //       MUX16 lut_4(F, INIT[0], ..., INIT[15], I0, I1, I2, I3);
    //   也就是 **选择下标 = I0 + 2*I1 + 4*I2 + 8*I3**（I0 是最低位）。
    //   取 INIT = 16'h8000 -> 只有 bit15 = 1 -> 只有"四个输入全 1"时 F=1。
    //   这正好把位序钉死：要是谁把 I0/I3 接反，这个检查立刻红。
    //==================================================================
    reg  la = 1'b0, lb = 1'b0, lc = 1'b0, ld = 1'b0;
    wire lf;

    LUT4 #(.INIT(16'h8000)) u_lut4 (
        .F  (lf),
        .I0 (la),
        .I1 (lb),
        .I2 (lc),
        .I3 (ld)
    );

    //==================================================================
    // 2) IOBUF —— 三态双向缓冲
    //
    //   实现：  buf    OB (O,  IO);      // O 始终跟随 IO
    //           bufif0 IB (IO, I, OEN);  // OEN=0 时把 I 驱动到 IO（低有效）
    //   板上用途：双向口 / 开漏总线那种场景。
    //   tb 侧用一个 `ext_low` 模拟"对端把线拉低"，用 pullup 模拟板上上拉。
    //==================================================================
    reg  io_i    = 1'b0;
    reg  io_oen  = 1'b1;      // 1 = 释放（输入模式）
    reg  ext_low = 1'b0;      // 1 = 对端把线拉低
    wire io_line;
    wire io_o;

    IOBUF u_iobuf (
        .O   (io_o),
        .IO  (io_line),
        .I   (io_i),
        .OEN (io_oen)
    );

    pullup pu_io (io_line);                                  // 模拟板上上拉
    assign io_line = ext_low ? 1'b0 : 1'bz;                   // 模拟对端驱动

    //==================================================================
    // 3) GSR —— 全局复位（只有输入端口，例化即证明单元存在）
    //==================================================================
    GSR u_gsr (.GSRI (1'b0));

    //==================================================================
    // 4) OSC —— 内部振荡器
    //   模型：  half_clk = 2.381 * FREQ_DIV  (ns)
    //          FREQ_DIV=4 -> 半周期 9.524ns -> 约 52.5MHz
    //   只验证"在翻转"，不验证精确频率（那是器件手册的事）。
    //==================================================================
    wire    osc_out;
    integer osc_edges = 0;

    OSC #(.FREQ_DIV (4)) u_osc (.OSCOUT (osc_out));

    always @(posedge osc_out) osc_edges = osc_edges + 1;

    //==================================================================
    // 工具
    //==================================================================
    initial begin
        log_fd = $fopen("gowin_prim_result.txt", "w");
        if (log_fd == 0) $display("[warn] 无法创建 gowin_prim_result.txt");
    end

    task check;
        input [1023:0] name;
        input integer got;
        input integer exp;
        begin
            checks = checks + 1;
            if (got !== exp) begin
                errors = errors + 1;
                $fwrite(log_fd, "  [FAIL] %0s : got=%0d exp=%0d\n", name, got, exp);
            end else begin
                $fwrite(log_fd, "  [ OK ] %0s : %0d\n", name, got);
            end
        end
    endtask

    task step;
        begin
            @(posedge clk);
            #1;
        end
    endtask

    //==================================================================
    // 主流程
    //==================================================================
    integer e0;

    initial begin
        $fwrite(log_fd, "=== tb_gowin_prim: Gowin 原语库 ↔ ModelSim 链路冒烟 ===\n");
        $fwrite(log_fd, "  [info] 本 tb 例化真实 Gowin 原语（LUT4/IOBUF/GSR/OSC）。\n");
        $fwrite(log_fd, "  [info] 库缺失 / 版本不对 / 路径不对 -> 编译或 elaborate 会直接失败。\n");
        $fwrite(log_fd, "  [info] 判版本：库里有 MODULE DQS = V1.9.11 建的（过期）；没有 = V1.9.12。\n");

        //------------------------------------------------------------------
        // 自检：两个输入初值先确认（防止 tb 自己写错常量）
        //------------------------------------------------------------------
        $fwrite(log_fd, "\n--- 0. 起步状态 ---\n");
        step;
        check("0.1 IOBUF 释放 + 上拉 -> 线为高", (io_line === 1'b1) ? 1 : 0, 1);

        //------------------------------------------------------------------
        // 1. LUT4：INIT=16'h8000，只有 I3I2I1I0=1111 时 F=1
        //------------------------------------------------------------------
        $fwrite(log_fd, "\n--- 1. LUT4 查表（INIT=16'h8000）---\n");

        {la, lb, lc, ld} = 4'b0000; #1 step;   check("1.1 0000 -> F=0", lf, 0);
        {la, lb, lc, ld} = 4'b1000; #1 step;   check("1.2 1000 -> F=0", lf, 0);
        {la, lb, lc, ld} = 4'b0111; #1 step;   check("1.3 0111 -> F=0", lf, 0);
        {la, lb, lc, ld} = 4'b1110; #1 step;   check("1.4 1110 -> F=0", lf, 0);
        {la, lb, lc, ld} = 4'b1111; #1 step;   check("1.5 1111 -> F=1（位序正确）", lf, 1);
        {la, lb, lc, ld} = 4'b0000; #1 step;

        //------------------------------------------------------------------
        // 2. IOBUF：方向控制 + 释放 + O 跟随 IO
        //------------------------------------------------------------------
        $fwrite(log_fd, "\n--- 2. IOBUF 三态 ---\n");

        io_oen = 1'b0; io_i = 1'b1; ext_low = 1'b0; #1 step;
        check("2.1 OEN=0 I=1 -> 驱动线为高", (io_line === 1'b1) ? 1 : 0, 1);
        check("2.2 OEN=0 I=1 -> O=1",        (io_o    === 1'b1) ? 1 : 0, 1);

        io_i = 1'b0; #1 step;
        check("2.3 OEN=0 I=0 -> 驱动线为低", (io_line === 1'b0) ? 1 : 0, 1);
        check("2.4 OEN=0 I=0 -> O=0",        (io_o    === 1'b0) ? 1 : 0, 1);

        io_oen = 1'b1; io_i = 1'b1; ext_low = 1'b0; #1 step;
        check("2.5 OEN=1 释放 -> 靠上拉为高", (io_line === 1'b1) ? 1 : 0, 1);
        check("2.6 OEN=1 O 跟随 IO(高)",      (io_o    === 1'b1) ? 1 : 0, 1);

        ext_low = 1'b1; #1 step;
        check("2.7 OEN=1 对端拉低 -> 线为低", (io_line === 1'b0) ? 1 : 0, 1);
        check("2.8 OEN=1 O 跟随 IO(低)",      (io_o    === 1'b0) ? 1 : 0, 1);

        ext_low = 1'b0; io_oen = 1'b1; #1 step;

        //------------------------------------------------------------------
        // 3. GSR：能走到这里就说明它 elaborate 成功了
        //------------------------------------------------------------------
        $fwrite(log_fd, "\n--- 3. GSR ---\n");
        check("3.1 GSR 例化成功（能跑到这里即证明）", 1, 1);

        //------------------------------------------------------------------
        // 4. OSC：真的在翻转
        //    FREQ_DIV=4 -> 半周期 9.524ns；2000ns 内应有 ~105 个上升沿。
        //    下限取 50（很宽松），只要"没在翻转"就必红。
        //------------------------------------------------------------------
        $fwrite(log_fd, "\n--- 4. OSC 振荡器 ---\n");
        e0 = osc_edges;
        #2000;
        check("4.1 OSC 2000ns 内上升沿 >= 50", ((osc_edges - e0) >= 50) ? 1 : 0, 1);
        check("4.2 OSCOUT 不是 x",             ((osc_out === 1'b0) || (osc_out === 1'b1)) ? 1 : 0, 1);

        //------------------------------------------------------------------
        // 汇总
        //------------------------------------------------------------------
        $fwrite(log_fd, "\n=== tb_gowin_prim: %0d checks, %0d errors ===\n",
                checks, errors);
        if (errors == 0) $fwrite(log_fd, "RESULT: PASS\n");
        else             $fwrite(log_fd, "RESULT: FAIL\n");
        $fclose(log_fd);
        $stop;
    end

    //------------------------------------------------------------------
    // 超时保护
    //------------------------------------------------------------------
    initial begin
        #2_000_000;                      // 2ms
        $fwrite(log_fd, "RESULT: FAIL (timeout)\n");
        $fclose(log_fd);
        $stop;
    end

endmodule
